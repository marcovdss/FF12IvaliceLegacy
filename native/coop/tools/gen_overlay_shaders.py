"""Compile the overlay's HLSL (src/overlay/overlay.hlsl) to DXBC into src/overlay/shaders.inc (host tool, not part of
the DLL).

The compiler is Windows' own System32\\d3dcompiler_47.dll, called through ctypes (D3DCompile): MSYS2 g++ has no
fxc, and the DLL must not compile shaders at run time (no d3dcompiler import). The output records the HLSL's sha256,
the compiler file's version and sha256 and the generator version; build.py fails when the HLSL no longer matches the
recorded digest (regenerate after an intended change).

  python gen_overlay_shaders.py            rewrite src/overlay/shaders.inc
  python gen_overlay_shaders.py --check    exit 1 if the HLSL changed since shaders.inc was generated
"""
from __future__ import annotations

import argparse
import ctypes
import hashlib
import os
import sys
from ctypes import wintypes
from pathlib import Path

HERE = Path(__file__).resolve().parent
COOP = HERE.parent
HLSL = COOP / 'src' / 'overlay' / 'overlay.hlsl'
OUTPUT = COOP / 'src' / 'overlay' / 'shaders.inc'
GENERATOR_VERSION = 1
ENTRIES = [('vs_main', 'vs_4_0', 'VS'), ('ps_main', 'ps_4_0', 'PS')]
D3DCOMPILE_OPTIMIZATION_LEVEL3 = 1 << 15
D3DCOMPILE_WARNINGS_ARE_ERRORS = 1 << 18


def hlsl_text() -> bytes:
    # The digest and the compile both see LF line ends, whatever the checkout's EOL setting.
    return HLSL.read_bytes().replace(b'\r\n', b'\n')


def hlsl_digest() -> str:
    return hashlib.sha256(hlsl_text()).hexdigest()


def compiler_path() -> Path:
    system = Path(os.environ.get('SystemRoot', r'C:\Windows')) / 'System32' / 'd3dcompiler_47.dll'
    if not system.is_file():
        raise SystemExit(f'{system} not found')
    return system


def blob_bytes(blob: ctypes.c_void_p) -> bytes:
    vtbl = ctypes.cast(ctypes.cast(blob, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
    get_ptr = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)(vtbl[3])
    get_size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vtbl[4])
    release = ctypes.WINFUNCTYPE(wintypes.ULONG, ctypes.c_void_p)(vtbl[2])
    data = ctypes.string_at(get_ptr(blob), get_size(blob))
    release(blob)
    return data


def compile_all() -> list[tuple[str, bytes]]:
    dll = ctypes.WinDLL(str(compiler_path()))
    d3dcompile = dll.D3DCompile
    d3dcompile.restype = ctypes.c_long
    d3dcompile.argtypes = [ctypes.c_void_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                           ctypes.c_char_p, ctypes.c_char_p, wintypes.UINT, wintypes.UINT,
                           ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    src = hlsl_text()
    out = []
    for entry, target, tag in ENTRIES:
        code = ctypes.c_void_p()
        errors = ctypes.c_void_p()
        hr = d3dcompile(src, len(src), b'overlay.hlsl', None, None, entry.encode(), target.encode(),
                        D3DCOMPILE_OPTIMIZATION_LEVEL3 | D3DCOMPILE_WARNINGS_ARE_ERRORS, 0, ctypes.byref(code),
                        ctypes.byref(errors))
        message = blob_bytes(errors).decode(errors='replace') if errors else ''
        if hr < 0 or not code:
            raise SystemExit(f'{entry} ({target}): D3DCompile failed 0x{hr & 0xFFFFFFFF:08X}\n{message}')
        out.append((tag, blob_bytes(code)))
    return out


def file_version(path: Path) -> str:
    try:
        size = ctypes.windll.version.GetFileVersionInfoSizeW(str(path), None)
        buf = ctypes.create_string_buffer(size)
        ctypes.windll.version.GetFileVersionInfoW(str(path), 0, size, buf)
        p = ctypes.c_void_p()
        n = wintypes.UINT()
        ctypes.windll.version.VerQueryValueW(buf, '\\', ctypes.byref(p), ctypes.byref(n))
        ms, ls = ctypes.cast(p, ctypes.POINTER(wintypes.DWORD))[2:4]
        return f'{ms >> 16}.{ms & 0xFFFF}.{ls >> 16}.{ls & 0xFFFF}'
    except Exception:  # noqa: BLE001 - information only
        return 'unknown'


def generate() -> str:
    blobs = compile_all()
    comp = compiler_path()
    lines = ['// GENERATED by native/coop/tools/gen_overlay_shaders.py from overlay.hlsl. Do not edit by hand.',
             f'// generator-version: {GENERATOR_VERSION}',
             f'// hlsl-sha256: {hlsl_digest()}',
             f'// compiler: d3dcompiler_47.dll {file_version(comp)} sha256 {hashlib.sha256(comp.read_bytes()).hexdigest()}',
             '#pragma once',
             f'#define ILC_OVERLAY_HLSL_SHA256 "{hlsl_digest()}"']
    for tag, data in blobs:
        lines.append(f'#define ILC_OVERLAY_{tag}_SIZE {len(data)}')
        lines.append(f'#define ILC_OVERLAY_{tag}_BYTES \\')
        for start in range(0, len(data), 24):
            lines.append('    ' + ''.join(f'0x{b:02X},' for b in data[start:start + 24]) + ' \\')
        lines.append('    /* end */')
    return '\n'.join(lines) + '\n'


def recorded_digest(text: str) -> str | None:
    for line in text.splitlines():
        if line.startswith('// hlsl-sha256: '):
            return line.split(': ', 1)[1].strip()
    return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args(argv)
    if args.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if recorded_digest(current) != hlsl_digest():
            print(f'{OUTPUT} was not generated from the current overlay.hlsl (run gen_overlay_shaders.py)',
                  file=sys.stderr)
            return 1
        print('shaders.inc is current')
        return 0
    text = generate()
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
