"""Copy the built-in HUD themes into the module's sources (host tool, not part of the DLL).

The artist's theme packages (theme.json + atlas/font.inc + atlas/theme.atlas, written by theme_convert.py) are the
inputs. For each built-in theme this writes src/overlay/themes/<id>/:

  font.inc         the converter's compiled-in form, byte for byte (LF)
  theme.json       the theme's tokens, byte for byte (LF)
  theme_json.inc   theme.json as a byte array (ILC_THEME_JSON_BYTES / _SIZE) for theme_builtin_<id>.cpp

and src/overlay/themes/themes.lock.json: every written file's sha256, the font.inc atlas digest, and the sha256 of the
source theme.atlas next to it (the runtime form players ship; not copied). build.py checks the lock (a drift fails the
build); --check does the same without writing.

  python gen_overlay_themes.py --from <themes folder>   rewrite src/overlay/themes/ from the artist's packages
  python gen_overlay_themes.py --check                  exit 1 if a file differs from the lock
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
COOP = HERE.parent
OUT = COOP / 'src' / 'overlay' / 'themes'
LOCK = OUT / 'themes.lock.json'
GENERATOR_VERSION = 1
THEMES = ['legacy-bold', 'legacy-humanist', 'legacy-crisp']   # built-in order: 0 is the default (Marco: C)


def lf(data: bytes) -> bytes:
    return data.replace(b'\r\n', b'\n')


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def json_inc(theme_id: str, data: bytes) -> bytes:
    lines = [f'// GENERATED by native/coop/tools/gen_overlay_themes.py from themes/{theme_id}/theme.json. Do not edit.',
             f'// theme-json-sha256: {sha(data)}', '#pragma once', f'#define ILC_THEME_JSON_SIZE {len(data)}',
             '#define ILC_THEME_JSON_BYTES \\']
    for start in range(0, len(data), 32):
        lines.append('    ' + ''.join(f'{b},' for b in data[start:start + 32]) + ' \\')
    lines.append('    /* end */')
    return ('\n'.join(lines) + '\n').encode('ascii')


def atlas_digest(font_inc: bytes) -> str:
    for line in font_inc.decode('utf-8').splitlines():
        if line.startswith('// atlas-digest: '):
            return line.split(': ', 1)[1].strip()
    raise SystemExit('font.inc has no atlas-digest line')


def outputs(source: Path) -> tuple[dict[Path, bytes], dict]:
    files: dict[Path, bytes] = {}
    lock = {'generator': 'native/coop/tools/gen_overlay_themes.py', 'generatorVersion': GENERATOR_VERSION,
            'order': THEMES, 'themes': {}}
    for theme_id in THEMES:
        root = source / theme_id
        theme_json = lf((root / 'theme.json').read_bytes())
        font_inc = lf((root / 'atlas' / 'font.inc').read_bytes())
        doc = json.loads(theme_json)
        if doc.get('id') != theme_id:
            raise SystemExit(f'{theme_id}: theme.json id is {doc.get("id")!r}')
        out = OUT / theme_id
        files[out / 'theme.json'] = theme_json
        files[out / 'font.inc'] = font_inc
        files[out / 'theme_json.inc'] = json_inc(theme_id, theme_json)
        atlas = root / 'atlas' / 'theme.atlas'
        lock['themes'][theme_id] = {
            'name': doc.get('name'),
            'atlasDigest': atlas_digest(font_inc),
            'sourceThemeAtlasSha256': sha(atlas.read_bytes()) if atlas.is_file() else None,
            'files': {name: sha(files[out / name]) for name in ('theme.json', 'font.inc', 'theme_json.inc')},
        }
    return files, lock


def check() -> list[str]:
    if not LOCK.is_file():
        return [f'{LOCK} is missing']
    lock = json.loads(LOCK.read_text(encoding='utf-8'))
    problems = []
    for theme_id in THEMES:
        entry = lock.get('themes', {}).get(theme_id)
        if entry is None:
            problems.append(f'{theme_id}: not in the lock')
            continue
        for name, want in entry['files'].items():
            path = OUT / theme_id / name
            if not path.is_file():
                problems.append(f'{theme_id}/{name}: missing')
            elif sha(lf(path.read_bytes())) != want:
                problems.append(f'{theme_id}/{name}: differs from the lock')
        inc = OUT / theme_id / 'font.inc'
        if inc.is_file() and atlas_digest(lf(inc.read_bytes())) != entry['atlasDigest']:
            problems.append(f'{theme_id}/font.inc: atlas digest differs from the lock')
    return problems


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--from', dest='source', type=Path, help="the artist's themes folder (one folder per theme)")
    parser.add_argument('--check', action='store_true', help='compare src/overlay/themes with the lock')
    args = parser.parse_args(argv)
    if args.check:
        problems = check()
        for p in problems:
            print(p)
        return 1 if problems else 0
    if args.source is None:
        parser.error('--from is required unless --check')
    files, lock = outputs(args.source.resolve())
    for path, data in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    LOCK.write_bytes((json.dumps(lock, indent=2) + '\n').encode('utf-8'))
    print(json.dumps({t: lock['themes'][t]['atlasDigest'] for t in THEMES}, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
