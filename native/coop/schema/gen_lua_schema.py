"""Generate the Lua view of the bridge schema: package/x64/scripts/IvaliceLegacy/coop/schema_data.lua.

The Lua codec, the bridge's HELLO check and the settings range checks read only this table, which is expanded from
schema/bridge-abi-v1.json, so the two sides cannot drift: a stale file is caught by a test and by the HELLO
schema-id comparison at run time. Debug-only ops (names starting TEST_) are left out on purpose.

    python gen_lua_schema.py            write the file
    python gen_lua_schema.py --check    exit 1 if the committed file differs
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from codec import Schema  # noqa: E402

OUT = Path(__file__).resolve().parents[3] / 'package/x64/scripts/IvaliceLegacy/coop/schema_data.lua'


def render(s: Schema) -> str:
    j = s.json
    L = ['-- GENERATED by native/coop/schema/gen_lua_schema.py from schema/bridge-abi-v1.json. Do not edit.',
         'return {',
         f"  schema_sha256 = '{s.sha256}',",
         f"  schema_id = {{0x{s.sha256[:16]}, 0x{s.sha256[16:32]}}},",
         f"  abi_version = {j['abiVersion']},",
         f"  defaults_hex = '{j['defaults']['hex']}',",
         '  const = {']
    for k, v in s.const.items():
        L.append(f'    {k} = {v},')
    L.append('  },')
    L.append('  enums = {')
    for name, items in s.enums.items():
        L.append(f'    {name} = {{')
        for item, value in items.items():
            if item.startswith('TEST_'):
                continue
            L.append(f"      {item} = {value},")
        L.append('    },')
    L.append('  },')
    L.append('  structs = {')
    for name, st in s.structs.items():
        L.append(f"    {name} = {{id = {st['id']}, size = {st['size']}, fields = {{")
        for f in st['fields']:
            parts = [f"name = '{f['name']}'", f"kind = '{f['kind']}'", f"offset = {f['offset']}",
                     f"size = {f['size']}", f"count = {f['count']}", f"elem = {f['elemSize']}",
                     f"fid = {f['fieldId']}"]
            if f.get('type'):
                parts.append(f"type = '{f['type']}'")
            if f['kind'] in ('VAL', 'ARR'):
                parts.append(f"min = {f['min']}")
                parts.append(f"max = {f['max']}")
            L.append('      {' + ', '.join(parts) + '},')
        L.append('    }},')
    L.append('  },')
    L.append('}')
    return '\n'.join(L) + '\n'


def main() -> int:
    text = render(Schema())
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_bytes().replace(b'\r\n', b'\n').decode() == text
        print('schema_data.lua is current' if ok else 'schema_data.lua is STALE: run gen_lua_schema.py')
        return 0 if ok else 1
    OUT.write_text(text, newline='\n')
    print('wrote', OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
